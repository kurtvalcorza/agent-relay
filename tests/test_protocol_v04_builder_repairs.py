class ClaimMaturityRepairs(unittest.TestCase):
    def test_invalid_tokens_are_exact_not_substring_matches(self):
        for maturity in ("UNVERIFIED", "ASSERTEDLY"):
            with self.subTest(maturity=maturity):
                text = pass_with(
                    f"Claims / evidence maturity: parser: {maturity} @ abc123"
                )
                self.assertTrue(
                    any(f"unrecognized maturity {maturity}" in e for e in validate(text, kind="pass"))
                )

    def test_uppercase_acronyms_without_a_maturity_value_are_not_rejected(self):
        text = pass_with(
            "Claims / evidence maturity:",
            "- HTTP behavior still needs classification",
            "- JSON output remains to inspect",
        )
        self.assertEqual([], validate(text, kind="pass"))


class ReviewVocabularyRepairs(unittest.TestCase):
    def test_review_assurance_profile_is_validated(self):
        text = VALID_REVIEW.replace(
            "- Assurance profile: standard", "- Assurance profile: maximum"
        )
        self.assertIn("invalid assurance profile: maximum", validate(text, kind="review"))

    def test_review_mission_mode_is_validated(self):
        text = VALID_REVIEW.replace(
            "- Mission mode: understand", "- Mission mode: invent"
        )
        self.assertIn("invalid mission mode: invent", validate(text, kind="review"))


class FindingTableRepairs(unittest.TestCase):
    def test_explanatory_pipeline_after_completed_table_is_not_a_row(self):
        findings = (
            "| Finding | Observation/reviewed snapshot | State |\n"
            "|---|---|---|\n"
            "| F1 | abc123 | OPEN |\n\n"
            "Diagnostic example: `grep ERROR log | wc -l`."
        )
        self.assertEqual([], validate(handoff(findings), kind="handoff"))

    def test_extra_bullet_finding_after_table_is_refused(self):
        findings = (
            "| Finding | Observation/reviewed snapshot | State |\n"
            "|---|---|---|\n"
            "| F1 | abc123 | OPEN |\n\n"
            "- F2: parser can still drop data"
        )
        self.assertIn(
            "open findings after the finding table must not use prose/bullets; add each finding as a table row",
            validate(handoff(findings), kind="handoff"),
        )

    def test_separator_or_incomplete_states_are_rejected(self):
        for state in ("/", "/,", "OPEN/", "OPEN/DEFERRED/BLOCKED"):
            with self.subTest(state=state):
                findings = (
                    "| Finding | Observation/reviewed snapshot | State |\n"
                    "|---|---|---|\n"
                    f"| F1 | abc123 | {state} |"
                )
                self.assertTrue(
                    any("unrecognized finding state" in e for e in validate(handoff(findings), kind="handoff"))
                )


class CycleSemanticRepairs(unittest.TestCase):
    def test_no_new_findings_requires_a_ran_pass(self):
        for execution in ("FAILED", "SKIPPED", "N/A"):
            with self.subTest(execution=execution):
                text = pass_with(
                    f"Execution status: {execution}",
                    "Termination reason: NO_NEW_FINDINGS",
                )
                self.assertIn(
                    "termination reason NO_NEW_FINDINGS requires execution status RAN",
                    validate(text, kind="pass"),
                )
        # A termination reason is a cycle-level outcome, so the positive case
        # must name the cycle it reports on.
        self.assertEqual(
            [],
            validate(
                pass_with(
                    "Cycle ID: c1",
                    "Execution status: RAN",
                    "Termination reason: NO_NEW_FINDINGS",
                ),
                kind="pass",
            ),
        )

    def test_cycle_findings_require_continuity_or_immutable_ledger(self):
        text = BASE_PASS.replace("Findings: 0", "Findings: 1").replace(
            "Reviewed/modified snapshot: abc123",
            "Cycle ID: review-1\nReviewed/modified snapshot: abc123",
        )
        self.assertIn(
            "cycle pass with findings must carry per-finding continuity or an immutable Finding ledger",
            validate(text, kind="pass"),
        )

        with_ledger = text.replace(
            "Findings: 1", "Findings: 1\nFinding ledger: sha256:deadbeef"
        )
        self.assertNotIn(
            "cycle pass with findings must carry per-finding continuity or an immutable Finding ledger",
            validate(with_ledger, kind="pass"),
        )


class TemplateRepairs(unittest.TestCase):
    def test_decision_authority_classes_are_independently_assignable(self):
        text = (ROOT / "assets" / "HANDOFF.md").read_text()
        for authority in (
            "Mission",
            "Scope",
            "Architecture",
            "Acceptance",
            "Implementation",
            "Execution",
            "Evidence",
            "Readiness",
        ):
            with self.subTest(authority=authority):
                self.assertIn(f"- {authority}: <holder>", text)
        self.assertNotIn("- Mission/scope:", text)
        self.assertNotIn("- Implementation/execution:", text)

    def test_no_anchor_state_is_coherent_in_template(self):
        text = (ROOT / "assets" / "HANDOFF.md").read_text()
        self.assertIn("Immutable revision/digest: <immutable-id, digest, or N/A>", text)
        self.assertIn("Anchor gaps: <missing planning fields, none, or N/A>", text)

    def test_cycle_pass_template_carries_finding_continuity(self):
        text = (ROOT / "assets" / "AGENT-PASS.md").read_text()
        self.assertIn("Finding ledger:", text)
        self.assertIn("Finding continuity:", text)
        self.assertIn("observation=<immutable-id>", text)


